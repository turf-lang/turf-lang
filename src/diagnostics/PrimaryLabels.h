// The label for `Code`, or nullptr for a code with no row.
inline const char *defaultLabel(const char *Code) {
  if (!Code)
    return nullptr;
  for (const auto &Row : PrimaryLabels)
    if (std::strcmp(Row.Code, Code) == 0)
      return Row.Label;
  return nullptr;
}

