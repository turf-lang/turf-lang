#!/usr/bin/env python3
"""V-5 (issue #289): one registry of every diagnostic code.

`src/diagnostics/ErrorCodes.h` (AllErrorCodes) is the single source for the codes
the compiler emits. The table of them in docs/reference/cli_and_diagnostics.md,
between the `diagnostic-registry` markers, is GENERATED from it, so the page
cannot list a code the compiler lacks or miss one it has. The API-lock diff
(ROADMAP_v3.0.0.md 5.5.2) reads the same data with `--json`.

    scripts/check/diagnostic_registry.py --check    # CI: fail on any disagreement
    scripts/check/diagnostic_registry.py --write    # regenerate the page's block
    scripts/check/diagnostic_registry.py --json     # the registry as JSON, to stdout

`--check` fails when the page's block is not what `--write` would produce, or
when a code exists in one place and not another: registered but with no
docs/errors/codes page, a page for an unregistered code, an `ErrCode::`-style
"Exxx" literal in src/ or include/ that no row registers, or a code that
docs/reference/ names but the registry lacks (a typo such as E1633 or a code
that was never added). Run from anywhere; paths are relative to the repository.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HEADER = ROOT / "src/diagnostics/ErrorCodes.h"
PAGE = ROOT / "docs/reference/cli_and_diagnostics.md"
BEGIN = "<!-- diagnostic-registry:begin (generated by scripts/check/diagnostic_registry.py --write; do not edit) -->"
END = "<!-- diagnostic-registry:end -->"

CATEGORY_WORD = {
    "TYPE_MISMATCH": "type mismatch",
    "UNDECLARED_VAR": "undeclared variable",
    "CONTROL_FLOW": "control flow",
    "SYNTAX_ERROR": "syntax error",
    "ARITHMETIC": "arithmetic",
    "STRING_CONVERSION": "string conversion",
    "ARRAY_ERROR": "array error",
    "DECLARATION": "declaration",
    "FUNCTION_SIGNATURE": "function signature",
    "BUILTIN_FUNCTION": "builtin function",
    "MEMORY_ERROR": "memory error",
    "GENERAL": "general",
}

CONST_RE = re.compile(r'inline constexpr const char \*(\w+) = "(E\d{3})";')
ROW_RE = re.compile(
    r'^\s*\{\s*(ErrCode::\w+|"E\d{3}"),\s*"(\w+)",\s*"((?:[^"\\]|\\.)*)",\s*'
    r"SLM::ErrorCategory::(\w+)(?:\s*,\s*(true|false)(?:\s*,\s*(\d+))?)?\s*\},?\s*$",
    re.M,
)


def load():
    """The registry rows, in table order, as dicts."""
    text = HEADER.read_text()
    consts = dict(CONST_RE.findall(text))
    table = text[text.index("AllErrorCodes[] = {"):]
    rows = []
    for first, cls, desc, cat, important, since in ROW_RE.findall(table):
        code = consts[first[len("ErrCode::"):]] if first.startswith("ErrCode::") else first.strip('"')
        retired = "(retired" in desc
        # isWarningCode() (ErrorCodes.h): a class name ending in `Warning`.
        warning = cls.endswith("Warning")
        rows.append({
            "code": code,
            "class": cls,
            "kind": "warning" if warning else "error",
            "since": "2.%d" % int(since or 0),
            # What the build does with it before anyone names a level: a warning
            # starts at `warn` (LintLevels.h), an error has no level to choose.
            "level": "warn" if warning else "error",
            "category": CATEGORY_WORD[cat],
            "important": important == "true",
            "retired": retired,
            "description": desc,
        })
    return rows


def ranges(codes):
    """E001, E002, E003, E007 -> 'E001–E003, E007'."""
    nums = sorted(int(c[1:]) for c in codes)
    out, i = [], 0
    while i < len(nums):
        j = i
        while j + 1 < len(nums) and nums[j + 1] == nums[j] + 1:
            j += 1
        out.append("E%03d" % nums[i] if i == j else "E%03d–E%03d" % (nums[i], nums[j]))
        i = j + 1
    return ", ".join(out)


def render(rows):
    warnings = [r for r in rows if r["kind"] == "warning"]
    retired = [r for r in rows if r["retired"]]
    lines = [
        BEGIN,
        "",
        "%d codes, %s to %s: %d errors and %d warnings (%s). %d are retired (%s)."
        % (len(rows), rows[0]["code"], rows[-1]["code"], len(rows) - len(warnings),
           len(warnings), ranges([r["code"] for r in warnings]), len(retired),
           ranges([r["code"] for r in retired])),
        "",
        "| Code | Kind | Since | Level | Category | Name |",
        "|---|---|---|---|---|---|",
    ]
    for r in sorted(rows, key=lambda r: r["code"]):
        name = r["class"] + (" (retired)" if r["retired"] else "") + (" (important)" if r["important"] else "")
        lines.append("| %s | %s | %s | %s | %s | %s |"
                     % (r["code"], r["kind"], r["since"], r["level"], r["category"], name))
    lines += ["", END]
    return "\n".join(lines)


def page_with(block):
    text = PAGE.read_text()
    if BEGIN not in text or END not in text:
        raise SystemExit("diagnostic_registry: %s has no `diagnostic-registry` markers" % PAGE.relative_to(ROOT))
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return head + block + tail


def problems(rows):
    out = []
    registered = {r["code"] for r in rows}
    seen = set()
    for r in rows:
        if r["code"] in seen:
            out.append("%s has more than one registry row" % r["code"])
        seen.add(r["code"])
    expected = ["E%03d" % n for n in range(1, len(registered) + 1)]
    if sorted(registered) != expected:
        out.append("the codes are not E001..E%03d without a gap (missing: %s)"
                   % (len(registered), ", ".join(sorted(set(expected) - registered)) or "none"))

    for sub, what in (("docs/errors/codes", "the human page"), ("docs/slm/codes", "the SLM page")):
        pages = {p.stem for p in (ROOT / sub).glob("E[0-9][0-9][0-9].txt")}
        for code in sorted(registered - pages):
            out.append("%s is registered but has no %s %s/%s.txt" % (code, what, sub, code))
        for code in sorted(pages - registered):
            out.append("%s/%s.txt exists but %s is not in the registry (ErrorCodes.h)" % (sub, code, code))

    # A code spelled out in the compiler's sources that no row registers: it would
    # print a header `turf explain` cannot resolve.
    for base in ("src", "include"):
        for path in sorted((ROOT / base).rglob("*")):
            if path.suffix not in (".cpp", ".h") or path == HEADER:
                continue
            for n, line in enumerate(path.read_text(errors="replace").splitlines(), 1):
                for code in re.findall(r'"(E\d{3})"', line):
                    if code not in registered:
                        out.append("%s:%d names %s, which the registry lacks" % (path.relative_to(ROOT), n, code))

    # The reference pages name codes in prose and tables; every one must exist.
    for path in sorted((ROOT / "docs/reference").rglob("*.md")):
        text = path.read_text(errors="replace")
        if path == PAGE:
            # the generated block is checked by equality below, not by scanning it
            text = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), "", text, flags=re.S)
        for m in re.finditer(r"(?<![A-Za-z0-9_])E(\d{3})(?!\d)", text):
            code = "E" + m.group(1)
            line = text.count("\n", 0, m.start()) + 1
            window = text[max(0, m.start() - 40):m.end() + 40]
            # `E000` and `E999` are illustrative non-codes (`turf explain E999` is the example of an unknown one) in the reference.
            if code not in registered and code not in ("E000", "E999") and "E0NN" not in window:
                out.append("%s:%d names %s, which the registry lacks" % (path.relative_to(ROOT), line, code))

    want = page_with(render(rows))
    if PAGE.read_text() != want:
        out.append("%s's generated table is stale: run scripts/check/diagnostic_registry.py --write" % PAGE.relative_to(ROOT))
    return out


def main(argv):
    mode = argv[1] if len(argv) > 1 else "--check"
    rows = load()
    if len(rows) < 100:
        raise SystemExit("diagnostic_registry: parsed only %d rows from %s" % (len(rows), HEADER.relative_to(ROOT)))
    if mode == "--json":
        json.dump({"codes": sorted(rows, key=lambda r: r["code"])}, sys.stdout, indent=2, ensure_ascii=False)
        print()
    elif mode == "--write":
        PAGE.write_text(page_with(render(rows)))
        print("diagnostic_registry: wrote %d codes into %s" % (len(rows), PAGE.relative_to(ROOT)))
    elif mode == "--check":
        bad = problems(rows)
        for p in bad:
            print("diagnostic_registry: " + p)
        if bad:
            return 1
        print("diagnostic_registry: OK (%d codes; the reference table matches the registry)" % len(rows))
    else:
        print(__doc__)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
