#!/bin/bash
#
# gen_recipes.sh -- REL-003 stage 4: package-manager recipes for a release,
# generated from that release's checksums.txt so a recipe can never name an
# archive or a hash the release does not have.
#
#   homebrew/turf.rb     Homebrew formula   (macos-arm64, linux-x86_64, linux-arm64)
#   scoop/turf.json      Scoop manifest     (windows-x86_64)
#   aur/PKGBUILD         AUR `turf-bin`     (linux-x86_64, linux-arm64)
#   aur/.SRCINFO         its metadata, which the AUR requires beside it
#
# A recipe is written only for a platform the checksums actually list ("only
# for shipped platforms"). What this does not do: publish. The Homebrew, Scoop
# and AUR repositories are separate, need their own credentials, and are bumped
# by whoever owns them from these files; the release workflow attaches them to
# the release so there is one place to take them from.
#
# These install the archive's own layout (bin/ lib/ docs/ share/ in one tree,
# `turf` finding `turfc` and the install root from its real path), so each
# keeps the tree whole and links `turf` into the package manager's bin. The
# archives are self-contained (REL-008): the compiler needs only the C library.
#
# Usage: scripts/release/gen_recipes.sh --checksums FILE --version vX.Y.Z --out DIR
#            [--base-url URL]
#   --base-url   where the archives are (default the GitHub release for the tag)

set -eu

CHECKSUMS=""; VERSION=""; OUT=""
BASE_URL=""
while [ $# -gt 0 ]; do
  case "$1" in
    --checksums) CHECKSUMS="${2:?--checksums needs a file}"; shift 2 ;;
    --version) VERSION="${2:?--version needs a tag}"; shift 2 ;;
    --out) OUT="${2:?--out needs a directory}"; shift 2 ;;
    --base-url) BASE_URL="${2:?--base-url needs a URL}"; shift 2 ;;
    -h|--help) sed -n '3,27p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "gen_recipes.sh: unknown option '$1'" >&2; exit 2 ;;
  esac
done
[ -n "$CHECKSUMS" ] && [ -n "$VERSION" ] && [ -n "$OUT" ] || { echo "gen_recipes.sh: --checksums, --version and --out are required" >&2; exit 2; }
[ -f "$CHECKSUMS" ] || { echo "gen_recipes.sh: $CHECKSUMS not found" >&2; exit 1; }
case "$VERSION" in v*) TAG="$VERSION"; PLAIN="${VERSION#v}" ;; *) TAG="v$VERSION"; PLAIN="$VERSION" ;; esac
[ -n "$BASE_URL" ] || BASE_URL="https://github.com/turf-lang/turf-lang/releases/download/$TAG"

HOMEPAGE="https://github.com/turf-lang/turf-lang"
DESC="TurfLang: a statically typed, LLVM-backed, ahead-of-time compiled language"

# hash_of <platform> <ext>: the SHA-256 listed for turf-<tag>-<platform>.<ext>,
# empty when the release has no such archive. The name is matched whole, so
# `linux-x86_64` never picks up `linux-arch-x86_64`.
#
# A file name may carry a leading `*`: sha256sum on Windows writes
# `<hash> *<name>` (binary mode), so the windows zip's line has one and an
# exact compare silently found no hash, and v2.0.0-rc4's release had no Scoop
# manifest. Strip it before comparing.
hash_of() {
  awk -v n="turf-$TAG-$1.$2" '{ f = $2; sub(/^\*/, "", f) } f == n { print $1 }' "$CHECKSUMS"
}
url_of() { printf '%s/turf-%s-%s.%s\n' "$BASE_URL" "$TAG" "$1" "$2"; }

H_MAC=$(hash_of macos-arm64 tar.gz)
H_LIN=$(hash_of linux-x86_64 tar.gz)
H_LIN_ARM=$(hash_of linux-arm64 tar.gz)
H_WIN=$(hash_of windows-x86_64 zip)
if [ -z "$H_MAC$H_LIN$H_LIN_ARM$H_WIN" ]; then
  echo "gen_recipes.sh: $CHECKSUMS lists no turf-$TAG-* archive (is it this release's checksums.txt?)" >&2
  exit 1
fi

mkdir -p "$OUT/homebrew" "$OUT/scoop" "$OUT/aur"

# ---- Homebrew ---------------------------------------------------------------
if [ -n "$H_MAC$H_LIN$H_LIN_ARM" ]; then
  {
    echo "# Generated by scripts/release/gen_recipes.sh from the $TAG release's checksums.txt."
    echo "class Turf < Formula"
    echo "  desc \"$DESC\""
    echo "  homepage \"$HOMEPAGE\""
    echo "  version \"$PLAIN\""
    echo "  license \"Apache-2.0\""
    echo
    if [ -n "$H_MAC" ]; then
      echo "  on_macos do"
      echo "    on_arm do"
      echo "      url \"$(url_of macos-arm64 tar.gz)\""
      echo "      sha256 \"$H_MAC\""
      echo "    end"
      echo "  end"
    fi
    if [ -n "$H_LIN$H_LIN_ARM" ]; then
      echo "  on_linux do"
      if [ -n "$H_LIN" ]; then
        echo "    on_intel do"
        echo "      url \"$(url_of linux-x86_64 tar.gz)\""
        echo "      sha256 \"$H_LIN\""
        echo "    end"
      fi
      if [ -n "$H_LIN_ARM" ]; then
        echo "    on_arm do"
        echo "      url \"$(url_of linux-arm64 tar.gz)\""
        echo "      sha256 \"$H_LIN_ARM\""
        echo "    end"
      fi
      echo "  end"
    fi
    cat <<'EOF'

  def install
    # The archive is one tree (bin/ lib/ docs/ share/): `turf` finds `turfc`
    # beside it and `turfc` finds lib/std above it from their real paths, so
    # the tree stays whole in libexec and only the commands are linked.
    libexec.install Dir["*"]
    bin.install_symlink libexec/"bin/turf", libexec/"bin/turfc"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/turfc --version")
    (testpath/"hello.tr").write <<~TURF
      fn main(): int {
          printline("hello");
          return 0;
      }
    TURF
    assert_match "hello", shell_output("#{bin}/turf run hello.tr")
  end
end
EOF
  } > "$OUT/homebrew/turf.rb"
fi

# ---- Scoop ------------------------------------------------------------------
if [ -n "$H_WIN" ]; then
  # `extract_dir` because the zip has the archive's one top-level directory.
  cat > "$OUT/scoop/turf.json" <<EOF
{
    "version": "$PLAIN",
    "description": "$DESC",
    "homepage": "$HOMEPAGE",
    "license": "Apache-2.0",
    "architecture": {
        "64bit": {
            "url": "$(url_of windows-x86_64 zip)",
            "hash": "$H_WIN",
            "extract_dir": "turf-$TAG-windows-x86_64"
        }
    },
    "bin": [
        "bin\\\\turf.exe"
    ],
    "checkver": "github",
    "autoupdate": {
        "architecture": {
            "64bit": {
                "url": "$HOMEPAGE/releases/download/v\$version/turf-v\$version-windows-x86_64.zip",
                "extract_dir": "turf-v\$version-windows-x86_64"
            }
        },
        "hash": {
            "url": "$HOMEPAGE/releases/download/v\$version/checksums.txt"
        }
    }
}
EOF
fi

# ---- AUR --------------------------------------------------------------------
# `turf-bin`, from the same self-contained Linux archives as everything else:
# x86_64 and, when the release has it, aarch64 (Arch Linux ARM). The compiler
# needs only glibc. .SRCINFO is what the AUR reads; it is written here because
# the release is built on Ubuntu, which has no `makepkg --printsrcinfo`.
if [ -n "$H_LIN" ]; then
  AUR_VER=${PLAIN//-/_}
  AUR_ARCH="'x86_64'"
  [ -n "$H_LIN_ARM" ] && AUR_ARCH="'x86_64' 'aarch64'"
  {
    echo "# Generated by scripts/release/gen_recipes.sh from the $TAG release's checksums.txt."
    echo "pkgname=turf-bin"
    echo "pkgver=$AUR_VER"
    echo "pkgrel=1"
    echo "pkgdesc=\"$DESC\""
    echo "arch=($AUR_ARCH)"
    echo "url=\"$HOMEPAGE\""
    echo "license=('Apache-2.0')"
    echo "depends=('glibc')"
    echo "provides=('turf')"
    echo "conflicts=('turf')"
    echo "options=('!strip' '!debug')"
    echo "source_x86_64=(\"$(url_of linux-x86_64 tar.gz)\")"
    echo "sha256sums_x86_64=('$H_LIN')"
    if [ -n "$H_LIN_ARM" ]; then
      echo "source_aarch64=(\"$(url_of linux-arm64 tar.gz)\")"
      echo "sha256sums_aarch64=('$H_LIN_ARM')"
    fi
    cat <<PKG

package() {
  # One tree, as in the archive: turf finds turfc and lib/std from its real
  # path, so /usr/bin only gets links.
  local dir
  case "\$CARCH" in
    aarch64) dir="turf-$TAG-linux-arm64" ;;
    *) dir="turf-$TAG-linux-x86_64" ;;
  esac
  install -dm755 "\$pkgdir/opt/turf" "\$pkgdir/usr/bin"
  cp -a "\$srcdir/\$dir/." "\$pkgdir/opt/turf/"
  ln -s /opt/turf/bin/turf "\$pkgdir/usr/bin/turf"
  ln -s /opt/turf/bin/turfc "\$pkgdir/usr/bin/turfc"
  install -Dm644 "\$srcdir/\$dir/LICENSE" "\$pkgdir/usr/share/licenses/\$pkgname/LICENSE"
}
PKG
  } > "$OUT/aur/PKGBUILD"
  {
    echo "pkgbase = turf-bin"
    printf '\tpkgdesc = %s\n' "$DESC"
    printf '\tpkgver = %s\n' "$AUR_VER"
    printf '\tpkgrel = 1\n'
    printf '\turl = %s\n' "$HOMEPAGE"
    printf '\tarch = x86_64\n'
    if [ -n "$H_LIN_ARM" ]; then printf '\tarch = aarch64\n'; fi
    printf '\tlicense = Apache-2.0\n'
    printf '\tdepends = glibc\n'
    printf '\tprovides = turf\n'
    printf '\tconflicts = turf\n'
    printf '\toptions = !strip\n\toptions = !debug\n'
    printf '\tsource_x86_64 = %s\n' "$(url_of linux-x86_64 tar.gz)"
    printf '\tsha256sums_x86_64 = %s\n' "$H_LIN"
    if [ -n "$H_LIN_ARM" ]; then
      printf '\tsource_aarch64 = %s\n' "$(url_of linux-arm64 tar.gz)"
      printf '\tsha256sums_aarch64 = %s\n' "$H_LIN_ARM"
    fi
    printf '\npkgname = turf-bin\n'
  } > "$OUT/aur/.SRCINFO"
fi

ls "$OUT"/*/* | sed "s|^|wrote |"
