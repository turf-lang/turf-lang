package lockfile

import (
	"bytes"
	"errors"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

const (
	c1 = "3f2a9c1e0000000000000000000000000000abcd"
	c2 = "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa"
	h1 = "sha256:1111111111111111111111111111111111111111111111111111111111111111"
	h2 = "sha256:2222222222222222222222222222222222222222222222222222222222222222"
)

func sample() *Lock {
	return &Lock{Packages: []Package{
		{Name: "jsonx", Source: GitSource("https://example.com/someone/jsonx"), Ref: "tag=v1.2.0", Commit: c1, Hash: h1},
		{Name: "geometry", Source: PathSource("../geometry")},
		{Name: "algo", Source: GitSource("/tmp/a b/algo.git"), Ref: "rev=3f2a9c1", Commit: c2, Hash: h2},
	}}
}

func TestMarshalIsSortedAndFixedOrder(t *testing.T) {
	got := string(sample().Marshal())
	want := `# This file is generated by turf. Commit it; do not edit it.
version = 1

[[package]]
name = "algo"
source = "git+/tmp/a b/algo.git"
ref = "rev=3f2a9c1"
commit = "` + c2 + `"
hash = "` + h2 + `"

[[package]]
name = "geometry"
source = "path+../geometry"

[[package]]
name = "jsonx"
source = "git+https://example.com/someone/jsonx"
ref = "tag=v1.2.0"
commit = "` + c1 + `"
hash = "` + h1 + `"
`
	if got != want {
		t.Fatalf("Marshal:\n%s\nwant:\n%s", got, want)
	}
}

func TestRoundTrip(t *testing.T) {
	first := sample().Marshal()
	back, err := Parse("turf.lock", first)
	if err != nil {
		t.Fatal(err)
	}
	if again := back.Marshal(); !bytes.Equal(first, again) {
		t.Fatalf("write-read-write changed the bytes:\n%s\n%s", first, again)
	}
	if p := back.Find("jsonx"); p == nil || p.Commit != c1 || p.Ref != "tag=v1.2.0" || p.GitURL() != "https://example.com/someone/jsonx" {
		t.Fatalf("jsonx read back wrong: %+v", p)
	}
	if back.Find("nope") != nil {
		t.Fatal("Find of an absent name must be nil")
	}
}

func TestMarshalIsIndependentOfInputOrder(t *testing.T) {
	a := sample()
	b := &Lock{Packages: []Package{a.Packages[2], a.Packages[0], a.Packages[1]}}
	if !bytes.Equal(a.Marshal(), b.Marshal()) {
		t.Fatal("the same set of packages in a different order must give the same bytes")
	}
}

func TestEmptyLockRoundTrips(t *testing.T) {
	out := (&Lock{}).Marshal()
	if string(out) != "# This file is generated by turf. Commit it; do not edit it.\nversion = 1\n" {
		t.Fatalf("empty lock: %q", out)
	}
	l, err := Parse("turf.lock", out)
	if err != nil || len(l.Packages) != 0 {
		t.Fatalf("empty lock read back: %v %+v", err, l)
	}
}

func TestSpecialCharactersSurvive(t *testing.T) {
	l := &Lock{Packages: []Package{{
		Name: "x", Source: GitSource("C:\\repos\\\"odd\"\tname"), Ref: "branch=feat/a\u00e9", Commit: c1, Hash: h1,
	}}}
	back, err := Parse("turf.lock", l.Marshal())
	if err != nil {
		t.Fatal(err)
	}
	if *back.Find("x") != l.Packages[0] {
		t.Fatalf("got %+v, want %+v", back.Packages[0], l.Packages[0])
	}
}

func TestParseErrors(t *testing.T) {
	git := func(extra string) string {
		return "version = 1\n[[package]]\nname = \"a\"\nsource = \"git+u\"\nref = \"tag=v\"\ncommit = \"" + c1 + "\"\nhash = \"" + h1 + "\"\n" + extra
	}
	tests := []struct{ name, text, frag string }{
		{"not toml", "version = ", "turf.lock:1"},
		{"no version", "[[package]]\nname = \"a\"\nsource = \"path+x\"\n", "missing `version`"},
		{"version type", "version = \"1\"\n", "`version` must be an integer"},
		{"future version", "version = 2\n", "version 2 is not supported"},
		{"top-level unknown key", "version = 1\nextra = 1\n", "unknown key `extra`"},
		{"package not tables", "version = 1\npackage = 3\n", "array of tables"},
		{"unknown key", git("colour = \"red\"\n"), "unknown key `colour`"},
		{"no name", "version = 1\n[[package]]\nsource = \"path+x\"\n", "missing `name`"},
		{"empty name", "version = 1\n[[package]]\nname = \"\"\nsource = \"path+x\"\n", "empty `name`"},
		{"name type", "version = 1\n[[package]]\nname = 3\nsource = \"path+x\"\n", "`name` must be a string"},
		{"no source", "version = 1\n[[package]]\nname = \"a\"\n", "missing `source`"},
		{"bad source scheme", "version = 1\n[[package]]\nname = \"a\"\nsource = \"registry+x\"\n", "must be path+<dir> or git+<url>"},
		{"empty git source", "version = 1\n[[package]]\nname = \"a\"\nsource = \"git+\"\n", "must be path+<dir> or git+<url>"},
		{"duplicate", "version = 1\n[[package]]\nname = \"a\"\nsource = \"path+x\"\n[[package]]\nname = \"a\"\nsource = \"path+y\"\n", "listed twice"},
		{"git without commit", "version = 1\n[[package]]\nname = \"a\"\nsource = \"git+u\"\nref = \"tag=v\"\nhash = \"" + h1 + "\"\n", "missing `commit`"},
		{"git without hash", "version = 1\n[[package]]\nname = \"a\"\nsource = \"git+u\"\nref = \"tag=v\"\ncommit = \"" + c1 + "\"\n", "missing `hash`"},
		{"git without ref", "version = 1\n[[package]]\nname = \"a\"\nsource = \"git+u\"\ncommit = \"" + c1 + "\"\nhash = \"" + h1 + "\"\n", "missing `ref`"},
		{"bad ref", strings.Replace(git(""), "tag=v", "release=v", 1), "must be tag=…, branch=… or rev=…"},
		{"abbreviated commit", strings.Replace(git(""), c1, "3f2a9c1", 1), "not a full 40-digit"},
		{"uppercase commit", strings.Replace(git(""), c1, strings.ToUpper(c1), 1), "not a full 40-digit"},
		{"bad hash", strings.Replace(git(""), h1, "md5:00", 1), "not sha256:<64 hex digits>"},
		{"path with commit", "version = 1\n[[package]]\nname = \"a\"\nsource = \"path+x\"\ncommit = \"" + c1 + "\"\n", "a path package, so `commit` does not apply"},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			_, err := Parse("turf.lock", []byte(tc.text))
			if err == nil {
				t.Fatalf("expected an error containing %q", tc.frag)
			}
			msg := err.Error()
			if !strings.Contains(msg, tc.frag) {
				t.Errorf("error %q lacks %q", msg, tc.frag)
			}
			if !strings.Contains(msg, "turf.lock") {
				t.Errorf("error %q does not name turf.lock", msg)
			}
			if !strings.Contains(msg, "hint: delete it and run `turf build` to regenerate it") {
				t.Errorf("error %q lacks the regenerate hint", msg)
			}
		})
	}
}

func TestReadDistinguishesMissingFromBad(t *testing.T) {
	dir := t.TempDir()
	if _, err := Read(filepath.Join(dir, "turf.lock")); !errors.Is(err, os.ErrNotExist) {
		t.Fatalf("a missing lock must be os.ErrNotExist, got %v", err)
	}
	p := filepath.Join(dir, "turf.lock")
	if err := os.WriteFile(p, sample().Marshal(), 0o644); err != nil {
		t.Fatal(err)
	}
	l, err := Read(p)
	if err != nil || len(l.Packages) != 3 {
		t.Fatalf("Read: %v %+v", err, l)
	}
}

func TestDiff(t *testing.T) {
	a := sample()
	if d := Diff(a, sample()); len(d) != 0 {
		t.Fatalf("identical locks differ: %v", d)
	}
	b := sample()
	b.Packages = b.Packages[:2]                                                         // drop algo
	b.Packages[0].Commit = c2                                                           // jsonx moved
	b.Packages = append(b.Packages, Package{Name: "new", Source: PathSource("../new")}) // added
	d := strings.Join(Diff(a, b), "\n")
	for _, frag := range []string{
		"removed 'algo' (git+/tmp/a b/algo.git rev=3f2a9c1)",
		"added 'new' (path+../new)",
		"changed 'jsonx': commit " + c1 + " -> " + c2,
	} {
		if !strings.Contains(d, frag) {
			t.Errorf("diff lacks %q:\n%s", frag, d)
		}
	}
	// A hash-only change is a change.
	c := sample()
	c.Packages[0].Hash = h2
	if d := Diff(a, c); len(d) != 1 || !strings.Contains(d[0], "hash ") {
		t.Fatalf("hash-only diff: %v", d)
	}
}
