package lockfile

import (
	"bufio"
	"fmt"
	"os"
	"strings"
)

type Entry struct {
	Name    string
	Version string
}

type Lockfile struct {
	Packages []Entry
}

func Write(path string, lf *Lockfile) error {
	f, err := os.Create(path)
	if err != nil {
		return err
	}
	defer f.Close()

	fmt.Fprintln(f, "# generated by turf. do not edit manually.")
	fmt.Fprintln(f, "")

	for _, pkg := range lf.Packages {
		fmt.Fprintln(f, "[[package]]")
		fmt.Fprintf(f, "name    = %q\n", pkg.Name)
		fmt.Fprintf(f, "version = %q\n", pkg.Version)
		fmt.Fprintln(f, "")
	}

	return nil
}

func Read(path string) (*Lockfile, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()

	lf := &Lockfile{}
	var current *Entry

	scanner := bufio.NewScanner(f)

	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())

		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}

		if line == "[[package]]" {
			if current != nil {
				lf.Packages = append(lf.Packages, *current)
			}
			current = &Entry{}
			continue
		}

		key, val, ok := parsePair(line)
		if !ok {
			continue
		}

		switch key {
		case "name":
			current.Name = val
		case "version":
			current.Version = val
		}
	}

	if current != nil {
		lf.Packages = append(lf.Packages, *current)
	}

	return lf, scanner.Err()
}

func parsePair(line string) (key, val string, ok bool) {
	parts := strings.SplitN(line, "=", 2)
	if len(parts) != 2 {
		return "", "", false
	}
	key = strings.TrimSpace(parts[0])
	val = strings.Trim(strings.TrimSpace(parts[1]), `"`)
	return key, val, true
}
