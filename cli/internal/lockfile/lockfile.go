// Package lockfile reads and writes turf.lock, the root project's record of
// exactly what a build used (docs/development/FREEZE.md 6.16, F-PKG-3): for
// every package except the root, where it came from and, for a git
// dependency, the commit and the tree hash it must still have.
//
// The file is written by turf and never edited by hand, so the writer is
// deterministic (packages sorted by name, fixed key order, no timestamps) and
// the reader is strict (an unknown version or key is an error, never a guess):
// a lock that is read leniently is a lock that silently stops pinning.
package lockfile

import (
	"fmt"
	"os"
	"regexp"
	"sort"
	"strings"

	"github.com/BurntSushi/toml"
)

// FileName is the name of the lockfile, beside the root turf.toml.
const FileName = "turf.lock"

// Version is the only format this package reads and writes.
const Version = 1

const header = "# This file is generated by turf. Commit it; do not edit it.\n"

// Package is one [[package]] entry.
type Package struct {
	Name   string
	Source string // "path+<dir relative to the project>" or "git+<url>"
	Ref    string // git only: "tag=…", "branch=…" or "rev=…", as the manifest asks
	Commit string // git only: the full 40-hex commit
	Hash   string // git only: "sha256:<hex>", the tree hash
}

// Lock is a parsed or about-to-be-written turf.lock.
type Lock struct {
	Packages []Package
}

// PathSource and GitSource build the `source` strings, so the spelling lives
// in one place.
func PathSource(rel string) string { return "path+" + rel }
func GitSource(url string) string  { return "git+" + url }

// IsGit reports whether the package is a git dependency.
func (p Package) IsGit() bool { return strings.HasPrefix(p.Source, "git+") }

// GitURL returns the repository URL of a git dependency.
func (p Package) GitURL() string { return strings.TrimPrefix(p.Source, "git+") }

// Find returns the entry named name, or nil. A nil Lock has no entries.
func (l *Lock) Find(name string) *Package {
	if l == nil {
		return nil
	}
	for i := range l.Packages {
		if l.Packages[i].Name == name {
			return &l.Packages[i]
		}
	}
	return nil
}

// Error is a lockfile the CLI cannot use. The hint is the same for every
// cause: the file is generated, so the fix is to regenerate it.
type Error struct{ Msg string }

func (e *Error) Error() string {
	return e.Msg + "\nhint: delete it and run `turf build` to regenerate it"
}

var (
	commitRe = regexp.MustCompile(`^[0-9a-f]{40}$`)
	hashRe   = regexp.MustCompile(`^sha256:[0-9a-f]{64}$`)
	refRe    = regexp.MustCompile(`^(tag|branch|rev)=.+$`)
)

// Marshal renders the lock. Entries are sorted by name and their keys are in a
// fixed order, so the same lock is the same bytes on every machine and a
// rebuild leaves the file untouched (an unchanged file means a clean `git
// status`, which is the point of committing it).
func (l *Lock) Marshal() []byte {
	pkgs := append([]Package(nil), l.Packages...)
	sort.Slice(pkgs, func(i, j int) bool { return pkgs[i].Name < pkgs[j].Name })
	var b strings.Builder
	b.WriteString(header)
	fmt.Fprintf(&b, "version = %d\n", Version)
	for _, p := range pkgs {
		b.WriteString("\n[[package]]\n")
		fmt.Fprintf(&b, "name = %s\n", quote(p.Name))
		fmt.Fprintf(&b, "source = %s\n", quote(p.Source))
		if p.IsGit() {
			fmt.Fprintf(&b, "ref = %s\n", quote(p.Ref))
			fmt.Fprintf(&b, "commit = %s\n", quote(p.Commit))
			fmt.Fprintf(&b, "hash = %s\n", quote(p.Hash))
		}
	}
	return []byte(b.String())
}

// quote writes a TOML basic string. strconv.Quote is not usable: it emits \a,
// \v and \x escapes, which TOML does not have.
func quote(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch {
		case r == '"':
			b.WriteString(`\"`)
		case r == '\\':
			b.WriteString(`\\`)
		case r == '\n':
			b.WriteString(`\n`)
		case r == '\t':
			b.WriteString(`\t`)
		case r == '\r':
			b.WriteString(`\r`)
		case r < 0x20 || r == 0x7f:
			fmt.Fprintf(&b, `\u%04X`, r)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

// Read reads and validates the lock at path. A missing file is returned as the
// underlying os error so the caller can tell "no lock yet" from "a bad lock".
func Read(path string) (*Lock, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	return Parse(path, data)
}

// Parse validates lock text. Every failure names the file.
func Parse(path string, data []byte) (*Lock, error) {
	bad := func(format string, a ...any) error {
		return &Error{Msg: path + ": " + fmt.Sprintf(format, a...)}
	}
	var raw map[string]any
	if _, err := toml.Decode(string(data), &raw); err != nil {
		if pe, ok := err.(toml.ParseError); ok && pe.Position.Line > 0 {
			return nil, &Error{Msg: fmt.Sprintf("%s:%d: %s", path, pe.Position.Line, pe.Message)}
		}
		return nil, bad("%v", err)
	}
	for _, k := range sortedKeys(raw) {
		if k != "version" && k != "package" {
			return nil, bad("unknown key `%s` at the top level", k)
		}
	}
	v, ok := raw["version"]
	if !ok {
		return nil, bad("missing `version`")
	}
	n, ok := v.(int64)
	if !ok {
		return nil, bad("`version` must be an integer")
	}
	if n != Version {
		return nil, bad("version %d is not supported by this turf (it reads version %d)", n, Version)
	}
	lock := &Lock{}
	list, present := raw["package"]
	if !present {
		return lock, nil
	}
	tables, ok := list.([]map[string]any)
	if !ok {
		return nil, bad("`package` must be an array of tables ([[package]])")
	}
	seen := map[string]bool{}
	for i, t := range tables {
		where := fmt.Sprintf("[[package]] number %d", i+1)
		get := func(key string, want bool) (string, error) {
			val, has := t[key]
			if !has {
				if want {
					return "", bad("%s is missing `%s`", where, key)
				}
				return "", nil
			}
			s, ok := val.(string)
			if !ok {
				return "", bad("%s: `%s` must be a string", where, key)
			}
			return s, nil
		}
		for _, k := range sortedKeys(t) {
			switch k {
			case "name", "source", "ref", "commit", "hash":
			default:
				return nil, bad("%s has an unknown key `%s`", where, k)
			}
		}
		var p Package
		var err error
		if p.Name, err = get("name", true); err != nil {
			return nil, err
		}
		if p.Name == "" {
			return nil, bad("%s has an empty `name`", where)
		}
		where = fmt.Sprintf("package '%s'", p.Name)
		if seen[p.Name] {
			return nil, bad("package '%s' is listed twice", p.Name)
		}
		seen[p.Name] = true
		if p.Source, err = get("source", true); err != nil {
			return nil, err
		}
		switch {
		case strings.HasPrefix(p.Source, "path+") && len(p.Source) > len("path+"):
			for _, k := range []string{"ref", "commit", "hash"} {
				if _, has := t[k]; has {
					return nil, bad("%s is a path package, so `%s` does not apply", where, k)
				}
			}
		case strings.HasPrefix(p.Source, "git+") && len(p.Source) > len("git+"):
			if p.Ref, err = get("ref", true); err != nil {
				return nil, err
			}
			if p.Commit, err = get("commit", true); err != nil {
				return nil, err
			}
			if p.Hash, err = get("hash", true); err != nil {
				return nil, err
			}
			if !refRe.MatchString(p.Ref) {
				return nil, bad("%s: `ref` %q must be tag=…, branch=… or rev=…", where, p.Ref)
			}
			if !commitRe.MatchString(p.Commit) {
				return nil, bad("%s: `commit` %q is not a full 40-digit lowercase hex commit", where, p.Commit)
			}
			if !hashRe.MatchString(p.Hash) {
				return nil, bad("%s: `hash` %q is not sha256:<64 hex digits>", where, p.Hash)
			}
		default:
			return nil, bad("%s: `source` %q must be path+<dir> or git+<url>", where, p.Source)
		}
		lock.Packages = append(lock.Packages, p)
	}
	return lock, nil
}

// Diff describes how next differs from prev, one line per package, for
// `--locked`'s error. Sorted by name; empty when the two are the same.
func Diff(prev, next *Lock) []string {
	names := map[string]bool{}
	for _, p := range prev.Packages {
		names[p.Name] = true
	}
	for _, p := range next.Packages {
		names[p.Name] = true
	}
	sorted := make([]string, 0, len(names))
	for n := range names {
		sorted = append(sorted, n)
	}
	sort.Strings(sorted)
	var out []string
	for _, n := range sorted {
		a, b := prev.Find(n), next.Find(n)
		switch {
		case a == nil:
			out = append(out, fmt.Sprintf("added '%s' (%s)", n, describe(*b)))
		case b == nil:
			out = append(out, fmt.Sprintf("removed '%s' (%s)", n, describe(*a)))
		case *a != *b:
			var parts []string
			for _, f := range []struct{ what, x, y string }{
				{"source", a.Source, b.Source}, {"ref", a.Ref, b.Ref},
				{"commit", a.Commit, b.Commit}, {"hash", a.Hash, b.Hash},
			} {
				if f.x != f.y {
					parts = append(parts, fmt.Sprintf("%s %s -> %s", f.what, f.x, f.y))
				}
			}
			out = append(out, fmt.Sprintf("changed '%s': %s", n, strings.Join(parts, "; ")))
		}
	}
	return out
}

func describe(p Package) string {
	if p.IsGit() {
		return p.Source + " " + p.Ref
	}
	return p.Source
}

func sortedKeys(m map[string]any) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
